use super::super::colors::{hsl_to_rgb, srgb};
use roxmltree::Node;

fn percent(node: Node, attr: &str) -> Option<f64> {
    let value = node.attribute(attr)?;
    let fraction = if let Some(p) = value.strip_suffix('%') {
        p.parse::<f64>().ok()? / 100.
    } else {
        value.parse::<f64>().ok()? / 100_000.
    };
    fraction.is_finite().then(|| fraction.clamp(0., 1.))
}

pub(super) fn resolve(node: Node) -> Option<String> {
    let rgb = match node.tag_name().name() {
        "prstClr" => return preset(node.attribute("val")?).map(str::to_owned),
        "scrgbClr" => [
            percent(node, "r")?,
            percent(node, "g")?,
            percent(node, "b")?,
        ]
        .map(srgb),
        "hslClr" => {
            let hue = node.attribute("hue")?.parse::<i32>().ok()?;
            hsl_to_rgb(
                f64::from(hue.rem_euclid(21_600_000)) / 3_600_000.,
                percent(node, "sat")?,
                percent(node, "lum")?,
            )
        }
        _ => return None,
    };
    let [r, g, b] = rgb.map(|v| (v * 255.).round() as u8);
    Some(format!("#{r:02x}{g:02x}{b:02x}"))
}

